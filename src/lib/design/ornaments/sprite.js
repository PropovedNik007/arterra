import { ornament } from './geometry.js';
import { ORNAMENT_PRESETS } from './presets.js';

/**
 * Layer styles baked into the sprite. Elements cloned by an external `<use>`
 * cannot be reached by the page's CSS, so the per-layer weights live here as
 * presentation attributes; colour (`currentColor`) and overall alpha are
 * inherited from the referencing `<svg>`.
 */
const LAYERS = {
	travel: 'stroke-width="0.7" stroke-opacity="0.55" stroke-dasharray="3 6"',
	infill: 'stroke-width="0.7" stroke-opacity="0.7"',
	perimeter: 'stroke-width="1.1"',
	seams: 'stroke-width="4"',
	/** Bands are only 1.5–2.5rem tall: smaller seam dots keep the eyelets clear. */
	bandSeams: 'stroke-width="2.5"'
};

/** @param {import('./geometry.js').Toolpath} toolpath */
export function seamPath(toolpath) {
	return toolpath.seams.map((p) => `M${p.x} ${p.y}h0`).join('');
}

/**
 * The ornament sprite: one `<g id="{preset}">` per static preset, each a slicer
 * preview in four layers (travel, infill, perimeters, seams).
 * @returns {string}
 */
export function renderSprite() {
	// The hero is printed inline from hero.json, so it needs no sprite group.
	const groups = Object.entries(ORNAMENT_PRESETS)
		.filter(([name]) => name !== 'hero')
		.map(([name, preset]) => {
			const toolpath = ornament(preset.motif, preset.options);
			if (toolpath.viewBox !== preset.viewBox) {
				throw new Error(
					`Ornament preset "${name}" declares ${preset.viewBox}, builds ${toolpath.viewBox}`
				);
			}
			const layer = (/** @type {keyof typeof LAYERS} */ kind, /** @type {string} */ d) =>
				d ? `<path vector-effect="non-scaling-stroke" ${LAYERS[kind]} d="${d}"/>` : '';
			return [
				`<g id="${name}" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">`,
				layer('travel', toolpath.travel.join('')),
				layer('infill', toolpath.infill.join('')),
				layer('perimeter', toolpath.perimeters.join('')),
				layer(toolpath.width > toolpath.height * 2 ? 'bandSeams' : 'seams', seamPath(toolpath)),
				'</g>'
			].join('');
		});
	return [
		'<svg xmlns="http://www.w3.org/2000/svg">',
		'<!-- Generated by scripts/build-ornaments.mjs from src/lib/design/ornaments; do not edit. -->',
		...groups,
		'</svg>',
		''
	].join('\n');
}

/** Full toolpath of the animated home hero, for `hero.json`. */
export function heroToolpath() {
	const { motif, options } = ORNAMENT_PRESETS.hero;
	return ornament(motif, options);
}
